-- 008_link_performance_to_forecast.sql
-- ===================================================
-- ربط سجلات التقييم بالتنبؤ الذي أنتجته جولتها.
--
-- الفجوة التي يسدّها: model_performance جدول تاريخي عمداً (صف لكل تقييم،
-- لتتبّع الأداء عبر الزمن). لكن لم يكن فيه ما يميّز جولة تقييم عن أخرى —
-- فتقييم نفس المنتج مرتين يُنتج صفوفاً متداخلة لا يمكن فصلها، والسؤال
-- "أي نموذج فاز *في آخر جولة*؟" يصبح بلا جواب: كل الصفوف تحمل is_best=1
-- من جولاتها المختلفة.
--
-- data_hash لا يكفي كبديل: نفس البيانات تُقيَّم مراراً (إعادة تشغيل،
-- تغيير أفق، إضافة نموذج)، فكل تلك الجولات تتشارك البصمة.
--
-- forecast_id يعرّف الجولة: كل save_result ينتج صف forecasts واحداً،
-- وكل صفوف التقييم المصاحبة تشير إليه. "آخر جولة" = أكبر forecast_id.
--
-- NULL مسموح: تقييم بلا تنبؤ محفوظ (مقارنة استكشافية) تصرّف مشروع.
-- SQLite يشترط أن يكون الافتراضي NULL عند إضافة عمود بمفتاح أجنبي.
-- ===================================================

ALTER TABLE model_performance
    ADD COLUMN forecast_id INTEGER REFERENCES forecasts(id) ON DELETE CASCADE;

-- "أرِني نماذج آخر جولة لهذا المنتج" — الاستعلام الذي دفع لهذا التغيير
CREATE INDEX IF NOT EXISTS idx_model_perf_forecast
    ON model_performance(forecast_id);
